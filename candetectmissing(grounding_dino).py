# Output folder for YOLO format bounding boxes
output_folder = "yolo_annotations"
os.makedirs(output_folder, exist_ok=True)

# Loop over all images
for image_name in image_files:
    image_path = os.path.join(dataset_folder, image_name)
    image = Image.open(image_path).convert("RGB")
    W, H = image.size

    # Process input with class labels
    inputs = processor(images=[image], text=list(class_mapping.keys()), return_tensors="pt").to(device)

    # Model inference
    with torch.no_grad():
        outputs = model(**inputs)

    # Post-process model outputs
    results = processor.post_process_grounded_object_detection(
        outputs,
        inputs.input_ids,
        threshold=0.5,
        text_threshold=0.3,
        target_sizes=[image.size[::-1]]
    )

    result = results[0]

    # Save to YOLO format
    output_file = os.path.join(output_folder, f"{os.path.splitext(image_name)[0]}.txt")
    with open(output_file, "w") as f:
        for box, label in zip(result["boxes"], result["labels"]):
            x_min, y_min, x_max, y_max = box.tolist()

            # Get class ID from label
            class_id = class_mapping.get(label, 0)  # Default to 0 if label not found

            # Convert to YOLO format
            x_center = ((x_min + x_max) / 2) / W
            y_center = ((y_min + y_max) / 2) / H
            width = (x_max - x_min) / W
            height = (y_max - y_min) / H

            # Write the YOLO line
            f.write(f"{class_id} {x_center:.6f} {y_center:.6f} {width:.6f} {height:.6f}\n")

print(f"YOLO format annotations saved in the '{output_folder}' folder.")

