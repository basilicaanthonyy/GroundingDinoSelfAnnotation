# Split person bbox into head, torso, and feet
def split_person_bbox(bbox, image_height, min_visible_height_ratio=0.6):
    x_min, y_min, x_max, y_max = bbox
    height = y_max - y_min
    bbox_bottom_visible = y_max >= int(image_height * min_visible_height_ratio)

    head = [x_min, y_min, x_max, int(y_min + 0.20 * height)]
    torso = [x_min, int(y_min + 0.20 * height), x_max, int(y_min + 0.80 * height)]
    feet = [x_min, int(y_min + 0.80 * height), x_max, y_max]

    regions = {"head": head, "torso": torso}
    if bbox_bottom_visible:
        regions["feet"] = feet
    return regions

# Draw bounding boxes and labels on the image
def draw_boxes_with_labels(image, detections, split_regions_list=None, save_path=None):
    fig, ax = plt.subplots(1, figsize=(10, 8))
    ax.imshow(image)

    for box, score, label in detections:
        x_min, y_min, x_max, y_max = box
        width, height = x_max - x_min, y_max - y_min

        rect = patches.Rectangle(
            (x_min, y_min), width, height, linewidth=2, edgecolor='red', facecolor='none'
        )
        ax.add_patch(rect)
        ax.text(
            x_min, y_min - 5,
            f"{label}: {round(score, 2)}",
            color='red', fontsize=10, fontweight='bold'
        )

    if split_regions_list:
        colors = {"head": "blue", "torso": "green", "feet": "purple"}
        for split_regions in split_regions_list:
            for region_name, region_box in split_regions.items():
                x_min, y_min, x_max, y_max = region_box
                width, height = x_max - x_min, y_max - y_min
                rect = patches.Rectangle(
                    (x_min, y_min), width, height,
                    linewidth=2, edgecolor=colors.get(region_name, 'gray'), facecolor='none'
                )
                ax.add_patch(rect)
                ax.text(
                    x_min, y_min - 5,
                    region_name,
                    color=colors.get(region_name, 'gray'), fontsize=10
                )

    plt.axis("off")

    if save_path:
        plt.savefig(save_path, bbox_inches='tight', pad_inches=0.1)

    plt.show()
    plt.close(fig)

