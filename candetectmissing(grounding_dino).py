def is_yellow_hardhat_present(head_box, other_boxes, other_labels, iou_threshold=0.1):
    def compute_iou(boxA, boxB):
        xA = max(boxA[0], boxB[0])
        yA = max(boxA[1], boxB[1])
        xB = min(boxA[2], boxB[2])
        yB = min(boxA[3], boxB[3])
        interArea = max(0, xB - xA) * max(0, yB - yA)

        boxAArea = (boxA[2] - boxA[0]) * (boxA[3] - boxA[1])
        boxBArea = (boxB[2] - boxB[0]) * (boxB[3] - boxB[1])
        iou = interArea / float(boxAArea + boxBArea - interArea + 1e-5)
        return iou

    for label, box in zip(other_labels, other_boxes):
        if label.lower() == "yellow hardhat":
            iou = compute_iou(head_box, list(map(int, box.tolist())))
            if iou >= iou_threshold:
                return True
    return False



